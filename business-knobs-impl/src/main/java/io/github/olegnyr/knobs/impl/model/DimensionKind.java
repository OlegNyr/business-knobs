package io.github.olegnyr.knobs.impl.model;

/**
 * Кто задаёт значения измерения — по этому админка понимает, откуда брать список значений при
 * вводе правила.
 */
public enum DimensionKind {

    /**
     * Значения заданы кодом и одинаковы на всех стендах (например, сегмент клиента).
     */
    CODE,

    /**
     * Значения свои на стенде, администратор ведёт их руками (например, ЦОД, арендатор).
     */
    STAND,

    /**
     * Значения берутся из другого справочника админки (например, каналы, сервисы).
     */
    REGISTRY
}
