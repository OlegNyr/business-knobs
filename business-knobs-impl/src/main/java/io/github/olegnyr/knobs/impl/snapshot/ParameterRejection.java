package io.github.olegnyr.knobs.impl.snapshot;

/**
 * Почему строка из админки не действует и действует значение файла. Закрытый
 * словарь: уходит в тег счётчика.
 */
public enum ParameterRejection {

    /**
     * Параметр удалён в админке.
     */
    DELETED,

    /**
     * Тип, признак списка или значение не читаются по каталогу сервиса.
     */
    TYPE,

    /**
     * В значении есть {@code ${...}}: подстановка бывает только в файле.
     */
    PLACEHOLDER
}
