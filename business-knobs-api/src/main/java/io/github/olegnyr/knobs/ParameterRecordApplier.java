package io.github.olegnyr.knobs;

import tools.jackson.databind.JsonNode;

import java.util.List;

/**
 * Применитель записей топика {@code knobs.parameters.v1} — SPI: сюда сервис
 * отдаёт записи своего потребителя Kafka. Реализацию даёт библиотека: {@code Knobs} без
 * Spring либо бин автоконфигурации.
 *
 * <p>Ключ вне каталога сервиса — пропуск, версия не новее действующей — игнор; пачка
 * сворачивается до старшей версии по ключу, событие смены на пачку одно.
 */
public interface ParameterRecordApplier {

    /**
     * Чем кончилось применение записи. Закрытый словарь: уходит в тег счётчика.
     */
    enum Outcome {

        /**
         * Запись применена.
         */
        APPLIED,

        /**
         * Запись удаления применена: действует значение файла.
         */
        DELETED,

        /**
         * Запись сохранена, но не читается по каталогу: действует значение файла.
         */
        REJECTED_TYPE,

        /**
         * В значении {@code ${...}}: действует значение файла.
         */
        REJECTED_PLACEHOLDER,

        /**
         * Тело записи не разбирается.
         */
        REJECTED_UNREADABLE,

        /**
         * Версия не больше версии в памяти.
         */
        IGNORED,

        /**
         * Реплика дописана версией, уже применённой в память при отказе базы.
         */
        REPAIRED,

        /**
         * Ключа нет в каталоге сервиса.
         */
        FOREIGN,

        /**
         * Рубильник включён: под работает на файле, записи топика не применяются.
         */
        SWITCHED_OFF
    }

    /**
     * Применяет запись.
     *
     * @param key  ключ записи — ключ параметра
     * @param body тело записи — слепок параметра с версией
     * @return исход применения
     */
    Outcome apply(String key, JsonNode body);

    /**
     * Применяет пачку записей: по ключу — только старшую версию, событие на пачку одно.
     *
     * @param records записи в порядке топика
     * @return исход на каждую запись, в том же порядке; свёрнутые записи — {@link Outcome#IGNORED}
     */
    List<Outcome> applyAll(List<ParameterTopicRecord> records);
}
